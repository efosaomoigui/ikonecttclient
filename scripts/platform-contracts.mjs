import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=path.resolve(fileURLToPath(new URL('..',import.meta.url)));
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const normalize=text=>text.replaceAll('\r\n','\n');
const pin='d0a300a2b5a17d63c637e71c71b523b88046a78f';
const blob=file=>execFileSync('git',['show',`${pin}:${file}`],{cwd:root,encoding:'utf8',maxBuffer:4*1024*1024});
const hash=text=>createHash('sha256').update(text).digest('hex');
const canonical=normalize(read('contracts/index.ts'));
assert.equal(canonical,blob('contracts/index.ts'),'Canonical schema differs from the reviewed v1.2.0 revision');
assert.equal(normalize(read('admin/vendor/contracts.ts')),canonical,'Admin schema snapshot differs from canonical');
assert.equal(normalize(read('my-ikonectt/vendor/index.ts')),canonical,'Portal schema snapshot differs from canonical');
for(const file of ['fixtures.ts','openapi.json','README.md','WALLET_HANDOFF.md','SETTLEMENT_HANDOFF.md'])assert.equal(normalize(read('my-ikonectt/vendor/'+file)),blob('contracts/'+file),'Portal committed snapshot mismatch: '+file);
const adminProvenance=JSON.parse(read('admin/vendor/provenance.json'));
assert.equal(adminProvenance.sourceCommit,pin);assert.equal(adminProvenance.contractVersion,'1.2.0');
assert.equal(adminProvenance.contractSha256,hash(blob('contracts/index.ts')));
assert.equal(adminProvenance.accessSha256,hash(blob('backend/src/identity/access.ts')));
assert.equal(normalize(read('backend/src/identity/access.ts')),blob('backend/src/identity/access.ts'));
const access=blob('backend/src/identity/access.ts').match(/export const ROLE_PERMISSIONS[^=]*= (\{[\s\S]*?\n\});/)[1];
assert.equal(normalize(read('admin/vendor/permissions.ts')),`// Generated from Agent 1 backend/src/identity/access.ts. Do not edit.\nexport const ROLE_PERMISSIONS = ${access} as const;\nexport type StaffRole = keyof typeof ROLE_PERMISSIONS;\nexport type Permission = typeof ROLE_PERMISSIONS[StaffRole][number];\n`);
assert.equal(JSON.parse(read('my-ikonectt/vendor/provenance.json')).commit,pin);
const spec=JSON.parse(read('contracts/openapi.json'));
assert.equal(spec.info.version,'1.2.0');
assert.equal(JSON.parse(read('contracts/package.json')).version,'1.2.0');
const operations=Object.entries(spec.paths).flatMap(([url,methods])=>Object.keys(methods).filter(method=>['get','post','patch'].includes(method)).map(method=>`${method.toUpperCase()} ${url}`));
assert.equal(Object.keys(spec.paths).length,78);assert.equal(operations.length,95);
assert.deepEqual(JSON.parse(read('admin/vendor/operations.json')).operations.sort(),operations.sort());
assert.equal(normalize(read('admin/vendor/SETTLEMENT_HANDOFF.md')),blob('contracts/SETTLEMENT_HANDOFF.md'));
console.log(JSON.stringify({status:'PASS',contractVersion:'1.2.0',canonicalCommit:pin,paths:78,operations:95,frontendSchemaAndPermissionParity:true}));
